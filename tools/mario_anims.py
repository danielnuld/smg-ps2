"""Generate engine/src/mario_anims.h from Petari's marioAnimeResourceTable / marioAnimeTable
(include/Game/Player/MarioAnimatorData.hpp): Mario::changeAnimation's name -> its BCK (lower case) and the table's
play rate (_4) and interpolation frames (_8), for every name with a file (the XanimeBckTable blends like 基本 have none).

Usage: python tools/mario_anims.py vendor/Petari engine/src/mario_anims.h"""
import re
import sys
from pathlib import Path


def tables(root):
    s = (Path(root) / "include/Game/Player/MarioAnimatorData.hpp").read_text(encoding="utf8")
    return [row for row in tables_all(s) if row[1]]


def tables_all(s):
    files = dict(re.findall(r'\{"([^"]+)"\},\s*//\s*mParent\s*\n\s*"([^"]*)",', s[s.index("XanimeBckTable1 "):]))
    i = s.index("XanimeGroupInfo marioAnimeTable[] = {")
    for n in re.findall(r'\{"([^"]+)"\},\s*//\s*mParent', s[i:s.index("\n};", i)]):
        files.setdefault(n, "")
    t = s[i:s.index("\n};", i)]  # (the aux / offset tables after it reuse the names)
    interp = {m.group(1): int(m.group(2), 0) for m in re.finditer(
        r'\{"([^"]+)"\},\s*//\s*mParent\s*\n\s*[0-9.]+f,\s*//\s*0x4\s*\n\s*(0x[0-9A-Fa-f]+|\d+),', t)}
    rate = {m.group(1): float(m.group(2)) for m in re.finditer(
        r'\{"([^"]+)"\},\s*//\s*mParent\s*\n\s*([0-9.]+)f,\s*//\s*0x4\s*\n', t)}
    return [(n, f.lower(), interp.get(n, 6), rate.get(n, 1.0)) for n, f in files.items()]


def main():
    root, out = sys.argv[1], sys.argv[2]
    rows = tables(root)
    assert len(rows) > 100, len(rows)
    lines = ["/* Generated by tools/mario_anims.py from Petari MarioAnimatorData.hpp (marioAnimeResourceTable: the BCK,",
             " * marioAnimeTable: _4 the play rate, _8 the interpolation frames) */", "#pragma once", "",
             "static const struct { const char *jp, *clip; unsigned char interp; float rate; } mario_anim_table[] = {"]
    lines += [f'    {{"{n}", "{f}", {i}, {r!r}f}},' for n, f, i, r in rows]
    lines += ["};", ""]
    # the blend groups (quadAnimeTable / tripleAnimeTable / doubleAnimeTable: XanimeBckTable4 / 3 / 2): their tracks'
    # BCKs and default weights, the interpolation and rate of their marioAnimeTable entry
    s = (Path(root) / "include/Game/Player/MarioAnimatorData.hpp").read_text(encoding="utf8")
    inter = {n: (i, r) for n, _, i, r in tables_all(s)}
    groups = []
    for m in re.finditer(r'\{"([^"]+)"\},\s*//\s*mParent\s*\n((?:\s*"[^"]*",\s*//\s*fileName\d\s*\n\s*[0-9.]+f,[^\n]*\n)+)',
                         s[:s.index("XanimeBckTable1 ")]):
        tr = re.findall(r'"([^"]*)",\s*//\s*fileName\d\s*\n\s*([0-9.]+)f,', m.group(2))
        tr = [(f.lower(), float(w)) for f, w in tr if f]
        if len(tr) > 1 and m.group(1) not in [g[0] for g in groups]:
            groups.append((m.group(1), tr))
    lines += ["static const struct { const char *jp, *clip[4]; float w[4]; unsigned char n, interp; float rate; } "
              "mario_anim_groups[] = {"]
    for n, tr in groups:
        i, r = inter.get(n, (6, 1.0))
        cl = ", ".join(f'"{f}"' for f, _ in tr) + ", NULL" * (4 - len(tr))
        ws = ", ".join(f"{w!r}f" for _, w in tr) + ", 0.0f" * (4 - len(tr))
        lines.append(f'    {{"{n}", {{{cl}}}, {{{ws}}}, {len(tr)}, {i}, {r!r}f}},')
    lines += ["};", ""]
    Path(out).write_text("\n".join(lines), encoding="utf8", newline="\n")
    print(f"{out}: {len(rows)} names")


if __name__ == "__main__":
    main()
