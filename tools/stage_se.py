"""engine/src/stage_se.inc from Petari's StageEffectDataTable.cpp: sStageEffectSeDataTable (start / moving / stop SE,
the stop SE's step, the riddle type) with sStageEffectPadDataTable's rumbles and the class that makes the name
(NameObjFactory), as the kind game.c plays it by.

usage (cwd the repo): python tools/stage_se.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "vendor/Petari/src/Game"
KIND = {"RailMoveObj": "R", "RailMoveObjPress": "R", "RailRotateMoveObj": "R", "RailMoveObjBreakAtEnd": "R",
        "RailMoveObjSwitchShadow": "R", "IceVolcanoUpDownPlane": "I", "RailDemoMoveObj": "D", "SideSpikeMoveStep": "K", "RotateMoveObj": "O",
        "AnmModelSwitchMove": "A", "AnmModelSwitchMoveEndKill": "A", "AnmModelGroundOnMove": "A",
        "AnmModelBindMove": "A", "AnmModelSwitchMoveEventCamera": "A", "SimpleMapObj": "S"}
PAD = {"nullptr": "-1", '"中"': "RUMBLE_MIDDLE", '"微弱"': "RUMBLE_VERY_WEAK", '"弱"': "RUMBLE_WEAK",
       '"強"': "RUMBLE_STRONG"}


def rows(t, table):
    body = t[t.index(table):]
    return re.findall(r'\{\s*"([^"]+)",([^}]*)\}', body[:body.index("};")])


def main():
    t = (SRC / "MapObj/StageEffectDataTable.cpp").read_text("utf-8")
    fac = (SRC / "NameObj/NameObjFactory.cpp").read_text("utf-8")
    cls = dict(re.findall(r'"(\w+)",\s*createNameObj<\s*([\w:]+)\s*>', fac))
    ids = set(re.findall(r"#define (SE_\w+)", (ROOT / "engine/src/se_ids.h").read_text()))
    pad = {n: [PAD[x.strip()] for x in rest.split(",")] for n, rest in rows(t, "sStageEffectPadDataTable[]")}
    out = ["/* Generated by tools/stage_se.py from Petari's StageEffectDataTable.cpp: do not edit. kind: the class that",
           " * makes the name (R the RailMoveObj family, I IceVolcanoUpDownPlane, D RailDemoMoveObj, K SideSpikeMoveStep,",
           " * O RotateMoveObj, A the AnmModelObj family, S SimpleMapObj, 0 a class that asks by name); pad: the start /",
           " * moving / stop rumble */",
           "static const struct { const char *name; u32 st, mv, ed; short steps; signed char type; char kind; signed char pad[3]; } stage_se[] = {"]
    names = set()
    for n, rest in rows(t, "sStageEffectSeDataTable[]"):
        st, mv, ed, steps, typ = [x.strip() for x in rest.split(",")]
        se = [x.strip('"') if x != "0" else "0" for x in (st, mv, ed)]
        assert all(x == "0" or x in ids for x in se), se
        k = KIND.get(cls.get(n, ""), "")
        out.append('    {"%s", %s, %s, %s, %s, %s, %s, {%s}},' % (n, se[0], se[1], se[2], steps, typ,
                                                                  "'%s'" % k if k else "0",
                                                                  ", ".join(pad.get(n, ["-1"] * 3))))
        names.add(n)
    assert set(pad) <= names, set(pad) - names
    (ROOT / "engine/src/stage_se.inc").write_bytes(("\n".join(out) + "\n};\n").encode("utf-8"))
    print(len(names), "rows")


if __name__ == "__main__":
    main()
