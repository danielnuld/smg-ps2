"""Generate engine/src/mario_const.h from Petari's MarioConstTable (include/Game/Player/MarioConst.hpp) and its
gMarioConstDefault initializer (src/Game/Player/MarioConst.cpp): every Mario constant with Petari's own name.
Usage: python tools/mario_const.py vendor/Petari engine/src/mario_const.h"""
import re
import sys

root, out = sys.argv[1], sys.argv[2]
hpp = open(f"{root}/include/Game/Player/MarioConst.hpp", encoding="utf-8").read()
cpp = open(f"{root}/src/Game/Player/MarioConst.cpp", encoding="utf-8").read()

body = re.search(r"struct MarioConstTable \{(.*?)\n\};", hpp, re.S).group(1)
types = {"f32": "float", "u16": "unsigned short", "s16": "short", "u8": "unsigned char", "s32": "int", "u32": "unsigned"}
fields = []
for t, name, dim in re.findall(r"^\s*/\* 0x[0-9A-F]+ \*/ (\w+) (\w+)(\[\d+\])?;", body, re.M):
    fields.append(f"    {types[t]} {name}{dim};")

init = re.search(r"gMarioConstDefault = \{(.*?)\};", cpp, re.S).group(1)
vals = re.findall(r"/\* (\w+) \*/ (\{[^}]*\}|[^,\n]+)", init)
assert len(vals) == len(fields), (len(vals), len(fields))

with open(out, "wb") as f:
    f.write(b"/* Generated by tools/mario_const.py from Petari MarioConst.hpp / MarioConst.cpp gMarioConstDefault */\n")
    f.write(b"#pragma once\n\nstruct MarioConstTable {\n")
    f.write(("\n".join(fields) + "\n};\n\n").encode())
    f.write(b"static const struct MarioConstTable MC = {\n")
    for name, v in vals:
        f.write(f"    .{name} = {v.strip()},\n".encode())
    f.write(b"};\n")
print(len(vals), "constants")
